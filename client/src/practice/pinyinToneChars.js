const tidy = syllable => String(syllable || '').trim().toLowerCase().normalize('NFC').replace(/ü|u:/g, 'v');

// The character to speak for a chart syllable (e.g. 'ma', 'lü', 'nüe') and tone 1-4, or '' when there is none.
export function toneCharacter(syllable, tone) {
  const key = tidy(syllable);
  const row = PINYIN_TONE_CHARS[key] || PINYIN_TONE_CHARS[key.replace(/^([nl])ue$/, '$1ve')];
  const ch = row ? row[tone - 1] : '';
  return ch && ch !== ' ' ? ch : '';
}
